// ── Sprachwahl aus der Anfrage (2026-09-30, „Missing Step" der Vorschau) ───────────────────
// Ursache (belegt): die Vorschau richtete sich nach der SEITEN-Sprache (fest en_US bzw. gar
// kein og:locale), nicht nach dem Leser. Der Server liest jetzt Accept-Language und wählt
// daraus eine der 26 WI-Sprachen (SUPPORTED); unbekannt → en. Bei en wird og:locale bewusst
// NICHT ausgegeben: WhatsApp/Facebook fallen dann selbst auf Englisch zurück.
const LOWER_SUPPORTED = new Map(SUPPORTED.map((code) => [code.toLowerCase(), code]));

/** Accept-Language-Kopfzeile → WI-Sprachcode aus SUPPORTED (unbekannt/leer → "en"). */
export function negotiateLanguage(header) {
  const candidates = [];
  String(header || "").split(",").forEach((part, index) => {
    const bits = String(part).split(";");
    const tag = bits[0].trim().toLowerCase().replace(/-/g, "_");
    if (!tag || tag === "*") return;
    let q = 1;
    for (const param of bits.slice(1)) {
      const m = /^\s*q\s*=\s*([0-9.]+)\s*$/i.exec(param);
      if (m) q = Number.parseFloat(m[1]);
    }
    if (!Number.isFinite(q) || q <= 0) return;
    candidates.push({ tag, q, index });
  });
  // q absteigend, bei gleichem q die Reihenfolge der Kopfzeile (der Leser meint die erste).
  candidates.sort((a, b) => (b.q - a.q) || (a.index - b.index));
  for (const { tag } of candidates) {
    const hit = LOWER_SUPPORTED.get(tag) || LOWER_SUPPORTED.get(tag.split("_")[0]);
    if (hit) return hit;
  }
  return "en";
}

/**
 * og:locale je WI-Sprache. Bewusst in der Form Sprache_REGION — die Open-Graph-Spezifikation
 * verlangt `ll_CC`, nicht den nackten Sprachcode. `en` ist null: der Tag fällt dann weg.
 */
const OG_LOCALE = {
  de: "de_DE", de_DE_formal: "de_DE", en: null,
  es: "es_ES", es_MX: "es_MX", fr: "fr_FR", af: "af_ZA", bg: "bg_BG", el: "el_GR",
  hi: "hi_IN", hr: "hr_HR", hu: "hu_HU", id: "id_ID", it: "it_IT", ja: "ja_JP",
  nb: "nb_NO", nl: "nl_NL", pl: "pl_PL", pt: "pt_BR", pt_PT: "pt_PT", ro: "ro_RO",
  ru: "ru_RU", tr: "tr_TR", uk: "uk_UA", ur: "ur_PK", zh: "zh_CN",
};

/** og:locale für einen WI-Sprachcode — null heißt: keinen Tag ausgeben. */
export function ogLocale(code) {
  const key = LOWER_SUPPORTED.get(String(code || "").toLowerCase()) || "en";
  return OG_LOCALE[key] || null;
}

/** Sprach-Teil eines WI-Codes, für hreflang ("de_DE_formal" → "de"). */
export function baseLanguage(code) {
  return String(code || "en").toLowerCase().split("_")[0] || "en";
}

/**
 * hreflang-Netz für eine Seite, die per Accept-Language ausliefert: es gibt genau EINE Adresse,
 * und die trägt alle Sprachen (dieselbe Seite in jeder Sprache — nichts wird dupliziert).
 * Deshalb x-default (→ Englisch, die Quelle), die gerade ausgelieferte Sprache und en —
 * nicht 26 Einträge auf dieselbe URL.
 */
export function hreflangLinks(lang, url) {
  const base = baseLanguage(lang);
  const links = [`<link rel="alternate" hreflang="x-default" href="${url}">`];
  if (base !== "en") links.push(`<link rel="alternate" hreflang="${base}" href="${url}">`);
  links.push(`<link rel="alternate" hreflang="en" href="${url}">`);
  return links;
}
